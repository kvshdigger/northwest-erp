import { test, expect } from '@playwright/test';

test.skip(process.env.PROJECT_PROGRESS_E2E !== '1', 'Requires isolated synthetic leave preview.');
test.use({ channel: process.env.PLAYWRIGHT_CHANNEL });

test('creates and edits a pending leave request in the V2 popup', async ({ page }) => {
    test.setTimeout(120000);
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/admin/v2/project-progress');
    await page.locator('input[type=email]').fill(process.env.PROJECT_PROGRESS_EMAIL!);
    await page.locator('input[type=password]').fill(process.env.PROJECT_PROGRESS_PASSWORD!);
    await Promise.all([page.waitForURL(url => !url.pathname.includes('/admin/login')), page.locator('input[type=password]').press('Enter')]);
    await page.goto('/admin/v2/project-progress');
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.getByRole('button', { name: 'Employees & HR', exact: true }).click();
    await page.getByRole('button', { name: 'Leave requests', exact: true }).click();
    await page.getByRole('button', { name: 'Create leave request', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const suffix = Date.now().toString();
    const day = new Date('2028-01-03T12:00:00Z');
    day.setUTCDate(day.getUTCDate() + Math.floor(Math.random() * 130) * 7);
    const date = day.toISOString().slice(0, 10);
    await dialog.getByRole('combobox', { name: 'Employee *', exact: true }).selectOption({ label: 'Local Demo HR Coach' });
    await dialog.getByRole('combobox', { name: 'Leave type *', exact: true }).selectOption({ label: 'V2 Demo Unallocated Leave' });
    await dialog.locator('[name=request_date_from]').fill(date);
    await dialog.locator('[name=request_date_to]').fill(date);
    await dialog.getByRole('textbox', { name: 'Description', exact: true }).fill('Synthetic leave ' + suffix);
    await dialog.getByRole('button', { name: 'Save leave request', exact: true }).click();
    await expect(dialog).toBeHidden();
    const row = page.locator('#peopleWorkspace tbody tr').filter({ hasText: 'Local Demo HR Coach' }).first();
    await row.getByRole('button', { name: 'View leave request', exact: true }).click();
    await expect(dialog).toContainText('1 working day');
    await expect(dialog.getByRole('button', { name: 'Approve current stage', exact: true })).toHaveCount(0);
    await dialog.getByRole('button', { name: 'Edit request', exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Description', exact: true }).fill('Updated synthetic leave ' + suffix);
    await dialog.getByRole('button', { name: 'Save leave request', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.reload();
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.getByRole('button', { name: 'Employees & HR', exact: true }).click();
    await page.getByRole('button', { name: 'Leave requests', exact: true }).click();
    await page.locator('#peopleWorkspace tbody tr').filter({ hasText: 'Local Demo HR Coach' }).first().getByRole('button', { name: 'View leave request', exact: true }).click();
    await expect(dialog.getByRole('textbox', { name: 'Description', exact: true })).toHaveValue('Updated synthetic leave ' + suffix);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(dialog.getByRole('button', { name: 'Edit request', exact: true })).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    if (process.env.NATIVE_LEAVE_SCREENSHOT) await page.screenshot({ path: process.env.NATIVE_LEAVE_SCREENSHOT });
    expect(errors).toEqual([]);
});
