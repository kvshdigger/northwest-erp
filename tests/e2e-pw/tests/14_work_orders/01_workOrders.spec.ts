import { test, expect } from '@playwright/test';

test.skip(process.env.PROJECT_PROGRESS_E2E !== '1','Requires the isolated preview and approved Finance demo permissions.');
test.use({channel:process.env.PLAYWRIGHT_CHANNEL});

test('connects an awarded Item and route to a quantity-limited subcon PO and tracker',async({page})=>{
    test.setTimeout(300000);
    const stamp=Date.now().toString(),item='Award item '+stamp,reference='WO-BROWSER-'+stamp,route='Award road '+stamp;
    const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('/admin/v2/project-progress');
    await page.locator('input[type=email]').fill(process.env.PROJECT_PROGRESS_EMAIL!);
    await page.locator('input[type=password]').fill(process.env.PROJECT_PROGRESS_PASSWORD!);
    await Promise.all([page.waitForURL(url=>!url.pathname.includes('/admin/login')),page.locator('input[type=password]').press('Enter')]);
    await page.goto('/admin/v2/project-progress');
    await page.getByRole('button',{name:'Finance',exact:true}).click();
    await page.locator('#financeWorkspace [data-section=items]').click();
    await page.getByRole('button',{name:'Create item',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await dialog.locator('[name=name]').fill(item);
    await dialog.locator('[name=type]').selectOption('service');
    await dialog.locator('[name=price]').fill('15');await dialog.locator('[name=cost]').fill('10');
    const firstOption=async(selector:string)=>dialog.locator(selector+' option').evaluateAll(nodes=>nodes.map(n=>(n as HTMLOptionElement).value).find(Boolean)!);
    await dialog.locator('[name=category_id]').selectOption(await firstOption('[name=category_id]'));
    const unit=await firstOption('[name=uom_id]');await dialog.locator('[name=uom_id]').selectOption(unit);await dialog.locator('[name=uom_po_id]').selectOption(unit);
    await dialog.getByRole('button',{name:'Save item',exact:true}).click();
    await expect(dialog.getByRole('heading',{name:item,exact:true})).toBeVisible();
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#financeWorkspace [data-section=work-orders]').click();
    await page.getByRole('button',{name:'New Work Order',exact:true}).click();
    const projectId=await firstOption('[name=project_id]');await dialog.locator('[name=project_id]').selectOption(projectId);
    await dialog.locator('[name=reference]').fill(reference);
    await dialog.locator('[name=partner_id]').selectOption(await firstOption('[name=partner_id]'));
    await dialog.locator('[name=currency_id]').selectOption({label:'MYR'});
    await dialog.locator('[name=title]').fill('Browser awarded works');await dialog.locator('[name=reason]').fill('Synthetic received award for integration test');
    await dialog.locator('[data-routes] [name=name]').fill(route);
    await dialog.locator('[data-routes] [name=chainage_from]').fill('0+000');await dialog.locator('[data-routes] [name=chainage_to]').fill('1+000');
    await dialog.locator('[data-items] [name=route_key]').selectOption(await firstOption('[data-items] [name=route_key]'));
    await dialog.locator('[data-items] [name=item_id]').selectOption({label:item});
    await dialog.locator('[data-items] [name=quantity]').fill('1000');await dialog.locator('[data-items] [name=maincon_rate]').fill('15');await dialog.locator('[data-items] [name=subcon_rate]').fill('10');
    await dialog.getByRole('button',{name:'Save Work Order draft',exact:true}).click();
    await dialog.getByRole('button',{name:'Review & approve',exact:true}).click();
    await dialog.getByRole('button',{name:'Approve Work Order version',exact:true}).click();
    await expect(dialog).toContainText('5000.00');
    await expect(dialog).toContainText('1000.0000');
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#financeWorkspace [data-section=purchase-orders]').click();
    await page.getByRole('button',{name:'Create purchase order',exact:true}).click();
    await expect(dialog.locator('[name=work_order_id]')).toBeVisible();
    await expect(dialog.locator('[name=work_order_id] option').filter({hasText:reference})).toHaveCount(1);
    const awardOption=await dialog.locator('[name=work_order_id] option').evaluateAll((nodes,ref)=>nodes.find(n=>n.textContent?.includes(ref))?.getAttribute('value')!,reference);
    await dialog.locator('[name=work_order_id]').selectOption(awardOption);
    await dialog.locator('[name=partner_id]').selectOption(await firstOption('[name=partner_id]'));
    await dialog.locator('[name=work_order_line_key]').selectOption(await firstOption('[name=work_order_line_key]'));
    await dialog.locator('[name=quantity]').fill('600');
    await dialog.getByRole('button',{name:'Save draft',exact:true}).click();
    await expect(dialog.getByRole('button',{name:'Edit purchase order',exact:true})).toBeVisible();
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.locator('#financeWorkspace [data-section=work-orders]').click();
    await page.locator('#financeWorkspace tbody tr').filter({hasText:reference}).getByRole('button',{name:'View Work Order',exact:true}).click();
    await expect(dialog).toContainText('400.0000');await expect(dialog).toContainText('6000.00');
    await expect(dialog.getByRole('button',{name:'Create variation',exact:true})).toBeVisible();
    if(process.env.WORK_ORDER_SCREENSHOT)await page.screenshot({path:process.env.WORK_ORDER_SCREENSHOT,fullPage:true});
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
    await dialog.getByRole('button',{name:'Close',exact:true}).click();
    await page.setViewportSize({width:1280,height:900});
    await page.getByRole('button',{name:'Project Tracker',exact:true}).click();
    await page.locator('#projectSelect').selectOption(projectId);
    await page.getByRole('button',{name:'New progress',exact:true}).click();
    const routeOption=await dialog.locator('#route option').evaluateAll((nodes,name)=>nodes.find(n=>n.textContent?.includes(name))?.getAttribute('value')!,route);
    await dialog.locator('#route').selectOption(routeOption);
    await expect(dialog.locator('#progressChainageFrom')).toHaveValue('0.000');
    await expect(dialog.locator('#progressChainageTo')).toHaveValue('1000.000');
    const routeLabels = await dialog.locator('#route option').allTextContents();
    expect(routeLabels.every(label => / · .+ v\d+ · /.test(label))).toBeTruthy();
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
    expect(errors).toEqual([]);
});
