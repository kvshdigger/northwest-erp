import { test, expect } from '@playwright/test';

test.skip(process.env.PROJECT_PROGRESS_E2E !== '1', 'Requires an isolated native-HR preview and synthetic HR manager.');
test.use({ channel: process.env.PLAYWRIGHT_CHANNEL });

test('creates and edits employee and department profiles entirely within V2', async ({ page }) => {
    test.setTimeout(150000);
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('/admin/v2/project-progress');
    await page.locator('input[type=email]').fill(process.env.PROJECT_PROGRESS_EMAIL!);
    await page.locator('input[type=password]').fill(process.env.PROJECT_PROGRESS_PASSWORD!);
    await Promise.all([page.waitForURL(url => !url.pathname.includes('/admin/login')), page.locator('input[type=password]').press('Enter')]);
    await page.goto('/admin/v2/project-progress');
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.getByRole('button', { name: 'Employees & HR', exact: true }).click();
    await page.getByRole('button', { name: 'Create employee', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const suffix = Date.now().toString();
    await dialog.getByRole('textbox', { name: 'Employee name *', exact: true }).fill('Native HR ' + suffix);
    await dialog.getByRole('textbox', { name: 'Work email', exact: true }).fill('native-hr+' + suffix + '@example.test');
    await dialog.getByRole('textbox', { name: 'Job title', exact: true }).fill('Site Coordinator');
    await dialog.getByRole('combobox', { name: 'Coach', exact: true }).selectOption({ label: 'Local Demo HR Coach' });
    await dialog.getByRole('textbox', { name: 'Identification number', exact: true }).fill('SYNTHETIC-PRIVATE-' + suffix);
    await dialog.getByRole('button', { name: 'Save employee', exact: true }).click();
    await expect(dialog).toBeHidden();
    const search = page.getByRole('textbox', { name: 'Search employee directory', exact: true });
    await search.fill('Native HR ' + suffix);
    await page.locator('#peopleWorkspace').getByRole('button', { name: 'Search', exact: true }).click();
    await expect(page.locator('#peopleWorkspace tbody tr')).toHaveCount(1);
    await expect(page.locator('#peopleWorkspace')).not.toContainText('SYNTHETIC-PRIVATE');
    await page.getByRole('button', { name: 'View profile', exact: true }).click();
    await expect(dialog.getByRole('textbox', { name: 'Identification number', exact: true })).toHaveValue('SYNTHETIC-PRIVATE-' + suffix);
    await dialog.getByRole('button', { name: 'Edit profile', exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Job title', exact: true }).fill('Senior Site Coordinator');
    await dialog.getByRole('button', { name: 'Save employee', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.reload();
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.getByRole('button', { name: 'Employees & HR', exact: true }).click();
    await search.fill('Native HR ' + suffix);
    await page.locator('#peopleWorkspace').getByRole('button', { name: 'Search', exact: true }).click();
    await expect(page.locator('#peopleWorkspace')).toContainText('Senior Site Coordinator');
    await page.getByRole('button', { name: 'Departments', exact: true }).click();
    await page.getByRole('button', { name: 'Create department', exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Department name *', exact: true }).fill('Native Department ' + suffix);
    await dialog.getByRole('button', { name: 'Save department', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.getByRole('textbox', { name: 'Search departments', exact: true }).fill('Native Department ' + suffix);
    await page.locator('#peopleWorkspace').getByRole('button', { name: 'Search', exact: true }).click();
    await page.getByRole('button', { name: 'View department', exact: true }).click();
    await dialog.getByRole('button', { name: 'Edit profile', exact: true }).click();
    await dialog.getByRole('textbox', { name: 'Department name *', exact: true }).fill('Updated Department ' + suffix);
    await dialog.getByRole('button', { name: 'Save department', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.getByRole('textbox', { name: 'Search departments', exact: true }).fill('Updated Department ' + suffix);
    await page.locator('#peopleWorkspace').getByRole('button', { name: 'Search', exact: true }).click();
    await expect(page.locator('#peopleWorkspace')).toContainText('Updated Department ' + suffix);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'View department', exact: true }).click();
    await expect(dialog.getByRole('button', { name: 'Edit profile', exact: true })).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    await expect(page).toHaveURL(/admin\/v2\/project-progress/);
    if (process.env.NATIVE_HR_SCREENSHOT) await page.screenshot({ path: process.env.NATIVE_HR_SCREENSHOT, fullPage: true });
    await dialog.getByRole('button', { name: 'Close', exact: true }).first().click();
    expect(errors).toEqual([]);
});
