import { test, expect, Page } from '@playwright/test';

test.skip(process.env.PROJECT_PROGRESS_E2E !== '1', 'Requires isolated HR workflows preview and synthetic reviewer.');
test.use({ channel: process.env.PLAYWRIGHT_CHANNEL });

async function login(page: Page, email: string) {
    await page.goto('/admin/v2/project-progress');
    await page.locator('input[type=email]').fill(email);
    await page.locator('input[type=password]').fill(process.env.PROJECT_PROGRESS_PASSWORD!);
    await Promise.all([page.waitForURL(url => !url.pathname.includes('/admin/login')), page.locator('input[type=password]').press('Enter')]);
    await page.goto('/admin/v2/project-progress');
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.getByRole('button', { name: 'Employees & HR', exact: true }).click();
}

test('uses attendance, private documents, checklists, Malaysia payroll and self-service in V2', async ({ page, browser }) => {
    test.setTimeout(480000);
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    const suffix = Date.now().toString();
    await login(page, process.env.PROJECT_PROGRESS_EMAIL!);
    await page.getByRole('button', { name: 'Attendance & timesheets', exact: true }).click();
    await page.getByRole('button', { name: 'New timesheet', exact: true }).click();
    let dialog = page.getByRole('dialog');
    const shift = new Date('2026-01-01T00:00:00Z'); shift.setUTCDate(shift.getUTCDate() + Math.floor(Math.random() * 200));
    const date = shift.toISOString().slice(0, 10);
    await dialog.getByRole('combobox', { name: 'Employee *', exact: true }).selectOption({ label: 'Local Demo HR Coach' });
    await dialog.getByRole('combobox', { name: 'Site / project *', exact: true }).selectOption({ index: 1 });
    await dialog.locator('[name=starts_at]').fill(date + 'T08:00');
    await dialog.locator('[name=ends_at]').fill(date + 'T17:00');
    await dialog.locator('[name=break_minutes]').fill('60');
    await dialog.locator('[name=overtime_minutes]').fill('60');
    await dialog.locator('[name=notes]').fill('Synthetic attendance ' + suffix);
    await dialog.getByRole('button', { name: 'Save record', exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page.locator('#peopleWorkspace')).toContainText('480 minutes worked');
    await page.getByRole('button', { name: 'Employment documents', exact: true }).click();
    await page.getByRole('button', { name: 'New document', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.locator('[name=title]').fill('Synthetic permit ' + suffix);
    await dialog.locator('[name=category]').fill('permit');
    await dialog.locator('[name=expires_on]').fill('2026-11-20');
    await dialog.locator('[name=attachment]').setInputFiles({ name: 'permit.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nSynthetic private permit\n%%EOF') });
    await dialog.getByRole('button', { name: 'Save record', exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page.locator('#peopleWorkspace')).toContainText('Synthetic permit ' + suffix);
    await page.getByRole('button', { name: 'Onboarding & offboarding', exact: true }).click();
    await page.getByRole('button', { name: 'New checklist', exact: true }).click();
    await dialog.locator('[name=title]').fill('Synthetic onboarding ' + suffix);
    await dialog.locator('[name=due_on]').fill('2026-12-01');
    await dialog.locator('[name=items]').fill('Verify permit\nIssue equipment');
    await dialog.getByRole('button', { name: 'Save record', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.locator('#peopleWorkspace tbody tr').filter({ hasText: 'Synthetic onboarding ' + suffix }).getByRole('button', { name: 'View', exact: true }).click();
    await dialog.locator('[data-reason]').fill('Permit checked');
    await dialog.getByRole('button', { name: 'Complete', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.getByRole('button', { name: 'Payroll & payslips', exact: true }).click();
    await page.getByRole('button', { name: 'Payroll configuration', exact: true }).click();
    await page.getByRole('button', { name: 'New configuration', exact: true }).click();
    await dialog.locator('[name=title]').fill('Malaysia rules ' + suffix);
    await expect(dialog.locator('[name=jurisdiction]')).toHaveValue('Malaysia');
    await expect(dialog.locator('[data-label]').first()).toHaveValue('EPF employee');
    await dialog.locator('[name=effective_from]').fill('2026-01-01');
    await dialog.locator('[name=effective_to]').fill('2026-12-31');
    await dialog.getByRole('button', { name: 'Save record', exact: true }).click();
    await expect(dialog).toBeHidden();

    const reviewContext = await browser.newContext({ baseURL: process.env.BASE_URL });
    const reviewer = await reviewContext.newPage();
    await login(reviewer, process.env.PROJECT_PROGRESS_REVIEWER_EMAIL || 'v2-hr-reviewer@example.test');
    await reviewer.getByRole('button', { name: 'Payroll & payslips', exact: true }).click();
    await reviewer.getByRole('button', { name: 'Payroll configuration', exact: true }).click();
    await reviewer.locator('#peopleWorkspace tbody tr').filter({ hasText: 'Malaysia rules ' + suffix }).getByRole('button', { name: 'View', exact: true }).click();
    const reviewDialog = reviewer.getByRole('dialog');
    await reviewDialog.locator('[data-reason]').fill('Synthetic configuration reviewed');
    await reviewDialog.getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(reviewDialog).toBeHidden();
    await page.getByRole('button', { name: 'Back to payroll', exact: true }).click();
    await page.getByRole('button', { name: 'New payroll draft', exact: true }).click();
    await dialog.locator('[name=rules_id]').selectOption({ label: 'Malaysia rules ' + suffix });
    await dialog.locator('[name=employee_id]').selectOption({ label: 'Demo Site Engineer' });
    await dialog.locator('[name=period_from]').fill(date);
    await dialog.locator('[name=period_to]').fill(date);
    await dialog.locator('[name=pay_date]').fill(date);
    await dialog.locator('[name=base_pay]').fill('3000.00');
    for (const line of await dialog.locator('[data-component]').all()) await line.locator('[data-value]').fill('1.00');
    await dialog.locator('[name=statutory_verified]').check();
    await dialog.getByRole('button', { name: 'Save draft', exact: true }).click();
    await expect(dialog).toBeHidden();
    await page.locator('#peopleWorkspace tbody tr').first().getByRole('button', { name: 'View', exact: true }).click();
    await dialog.locator('[data-reason]').fill('Synthetic payroll ready');
    await dialog.getByRole('button', { name: 'Submit', exact: true }).click();
    await expect(dialog).toBeHidden();
    await reviewer.getByRole('button', { name: 'Back to payroll', exact: true }).click();
    await reviewer.locator('#peopleWorkspace tbody tr').first().getByRole('button', { name: 'View', exact: true }).click();
    await reviewDialog.locator('[data-reason]').fill('Synthetic payroll totals independently checked');
    await reviewDialog.getByRole('button', { name: 'Approve', exact: true }).click();
    await expect(reviewDialog).toBeHidden();
    await reviewer.locator('#peopleWorkspace tbody tr').first().getByRole('button', { name: 'View', exact: true }).click();
    await expect(reviewDialog.getByRole('link', { name: 'Open / print payslip', exact: true })).toBeVisible();
    await reviewDialog.getByRole('button', { name: 'Close', exact: true }).first().click();
    await page.getByRole('button', { name: 'Employee self-service', exact: true }).click();
    await expect(page.locator('#peopleWorkspace')).toContainText('My employee workspace');
    await page.getByRole('button', { name: 'Edit my contact details', exact: true }).click();
    await dialog.locator('[name=emergency_contact]').fill('Synthetic contact ' + suffix);
    await dialog.getByRole('button', { name: 'Save contacts', exact: true }).click();
    await expect(dialog).toBeHidden();
    await expect(page.locator('#peopleWorkspace')).toContainText('Synthetic contact ' + suffix);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
    if (process.env.HR_WORKFLOWS_SCREENSHOT) await page.screenshot({ path: process.env.HR_WORKFLOWS_SCREENSHOT, fullPage: true });
    expect(errors).toEqual([]);
    await reviewContext.close();
});
