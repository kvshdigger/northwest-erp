import { test, expect } from '@playwright/test';

const enabled = process.env.PROJECT_PROGRESS_E2E === '1';
test.skip(!enabled, 'Requires an explicitly configured isolated V2 preview with assigned projects.');
test.use({ channel: process.env.PLAYWRIGHT_CHANNEL });

test('persists custom settings, routes and daily progress through the ERP session', async ({ page, browser }) => {
    const errors: string[] = [];
    page.on('pageerror', error => { errors.push(error.message); console.error('Workspace browser error:', error.message); });
    await page.goto('/admin/v2/project-progress');
    await page.getByLabel('Email address').fill(process.env.PROJECT_PROGRESS_EMAIL!);
    await page.locator('input[type="password"]').fill(process.env.PROJECT_PROGRESS_PASSWORD!);
    await Promise.all([page.waitForURL(url => !url.pathname.includes('/admin/login')), page.locator('input[type="password"]').press('Enter')]);
    await page.goto('/admin/v2/project-progress');
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    const project = await page.locator('#projectSelect').inputValue();
    const csrfFailure = await page.request.post('/admin/v2/project-progress/api/projects/' + project + '/routes', { data: { name: 'Rejected without CSRF' } });
    expect(csrfFailure.status()).toBe(419);
    const suffix = Date.now().toString();
    await page.getByText('Project setup', { exact: true }).click();
    await page.getByRole('button', { name: 'Add route', exact: true }).click();
    await page.locator('#setupRoute').fill('Browser route ' + suffix);
    await page.locator('#saveSetup').click();
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.locator('#trackerConfig').click();
    await page.locator('#addColumn').click();
    await page.locator('#activityName').fill('Browser measurement ' + suffix);
    await page.locator('#activityUnit').fill('m');
    await page.locator('.row-name').fill('Length installed');
    await page.locator('#saveDraft').click();
    await expect(page.locator('#settingsBackdrop')).toBeHidden();
    await page.reload();
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.locator('#trackerConfig').click();
    const row = page.locator('.config-row').filter({ hasText: 'Browser measurement ' + suffix });
    await expect(row).toContainText('DRAFT');
    await row.getByRole('button', { name: 'Settings' }).click();
    await expect(page.locator('#publishSettings')).toBeInViewport();
    await page.locator('[data-sample]').fill('12.5');
    await page.locator('#testFormula').click();
    await expect(page.locator('#formulaResult')).toContainText('12.500000');
    await page.locator('#publishSettings').click();
    await expect(page.locator('#settingsBackdrop')).toBeHidden();
    await row.getByRole('checkbox').uncheck();
    await page.reload();
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await page.locator('#trackerConfig').click();
    await expect(row.getByRole('checkbox')).not.toBeChecked();
    await row.getByRole('checkbox').check();
    await page.locator('[data-page="tracker"]').click();
    await page.locator('#trackerNew').click();
    await page.locator('#route').selectOption({ label: 'Browser route ' + suffix });
    await page.locator('#team').fill('Browser site team');
    const activity = page.locator('.section').filter({ hasText: 'Browser measurement ' + suffix });
    await activity.locator('.dynamic-input').fill('12.5');
    await page.route('**/api/projects/*/reports', async route => {
        const saved = await route.fetch();
        expect(saved.status()).toBe(201);
        await route.abort('failed');
    }, { times: 1 });
    await page.locator('#saveProgress').click();
    await expect(page.locator('#progressError')).toContainText('Connection interrupted');
    await page.locator('#saveProgress').click();
    await expect(page.locator('#modalBackdrop')).toBeHidden();
    await expect(page.locator('#trackerBody')).toContainText('12.500000 m');
    await page.reload();
    await expect(page.locator('#trackerBody')).toContainText('Browser route ' + suffix);
    await expect(page.locator('#trackerBody')).toContainText('Approved: 0.000000 m');
    const report = page.locator('#trackerBody tr').filter({ hasText: 'Browser route ' + suffix });
    await report.getByRole('button', { name: 'View entries' }).click();
    await expect(page.locator('#detailsBody')).toContainText('Length installed');
    await expect(page.locator('#detailsBody')).toContainText('12.500000');
    await expect(page.locator('#detailsBody .entry')).toHaveCount(1);
    await page.locator('#closeDetails').click();
    await page.locator('#projectSelect').selectOption({ index: 1 });
    await expect(page.locator('#connectionStatus')).toContainText('Connected ·');
    await expect(page.locator('#trackerBody')).not.toContainText('Browser route ' + suffix);
    await page.locator('#projectSelect').selectOption(project);
    await expect(page.locator('#trackerBody')).toContainText('Browser route ' + suffix);
    if (process.env.PROJECT_PROGRESS_MEMBER_NAME) {
        await page.getByText('Project setup', { exact: true }).click();
        await page.locator('#memberSetup').click();
        await page.locator('#setupUser').selectOption({ label: process.env.PROJECT_PROGRESS_MEMBER_NAME });
        await page.locator('#setupSubmit').uncheck();
        await page.locator('#setupConfigure').uncheck();
        await page.locator('#saveSetup').click();
        await expect(page.locator('#setupBackdrop')).toBeHidden();
        const context = await browser.newContext({ baseURL: process.env.BASE_URL });
        const member = await context.newPage();
        await member.goto('/admin/v2/project-progress');
        await member.locator('input[type=email]').fill(process.env.PROJECT_PROGRESS_MEMBER_EMAIL!);
        await member.locator('input[type=password]').fill(process.env.PROJECT_PROGRESS_MEMBER_PASSWORD!);
        await Promise.all([member.waitForURL(url => !url.pathname.includes('/admin/login')), member.locator('input[type=password]').press('Enter')]);
        await member.goto('/admin/v2/project-progress');
        await expect(member.locator('#connectionStatus')).toContainText('Connected ·');
        await expect(member.locator('#trackerNew')).toBeDisabled();
        await expect(member.locator('#memberSetup')).toBeHidden();
        await member.locator('#trackerConfig').click();
        await expect(member.locator('#addColumn')).toBeDisabled();
        await expect(member.locator('[data-settings]').first()).toBeDisabled();
        await context.close();
    }
    if (process.env.PROJECT_PROGRESS_DESKTOP_SCREENSHOT) await page.screenshot({ path: process.env.PROJECT_PROGRESS_DESKTOP_SCREENSHOT, fullPage: true });
    await expect(page.locator('#previousPage')).toBeDisabled();
    await expect(page.locator('#nextPage')).toBeDisabled();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#trackerNew').click();
    await expect(page.locator('#modalTitle')).toBeVisible();
    await expect(page.locator('#saveProgress')).toBeInViewport();
    await expect(page.locator('body')).toHaveClass(/modal-open/);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({ path: process.env.PROJECT_PROGRESS_SCREENSHOT || 'test-results/v2-connected-mobile.png', fullPage: true });
    await page.locator('#cancelModal').click();
    expect(errors).toEqual([]);
});
